def load_data():
    """
    Load the cleaned posts generated by data_wrangling.py.

    This script does NOT connect to PostgreSQL.
    """

    if not INPUT_FILE.exists():
        raise FileNotFoundError(
            f"Could not find:\n"
            f"{INPUT_FILE}\n\n"
            f"Run data_wrangling.py first."
        )

    df = pd.read_csv(
        INPUT_FILE,
        encoding="utf-8",
    )

    print("=" * 70)
    print("SIGNALFORGE EXPLORATORY DATA ANALYSIS")
    print("=" * 70)

    print("\nInput file:")
    print(f"    {INPUT_FILE}")

    print(f"\nRows loaded: {len(df):,}")
    print(f"Columns:     {len(df.columns):,}")

    return df


