# BASIC DATASET INFORMATION
# ============================================================

def basic_information(df):

    lines = [
        "=" * 70,
        "1. BASIC DATASET INFORMATION",
        "=" * 70,
        f"Rows:     {len(df):,}",
        f"Columns:  {len(df.columns):,}",
        "",
        "Columns:",
    ]

    for column in df.columns:
        lines.append(
            f"  - {column}"
        )

    # Current ingestion output uses post_id.
    if "post_id" in df.columns:

        lines.append(
            f"\nUnique post_id values: "
            f"{df['post_id'].nunique():,}"
        )

        lines.append(
            f"Duplicate post_id rows: "
            f"{df['post_id'].duplicated().sum():,}"
        )

    # Keep support for datasets that still contain `id`.
    elif "id" in df.columns:

        lines.append(
            f"\nUnique id values: "
            f"{df['id'].nunique():,}"
        )

        lines.append(
            f"Duplicate id rows: "
            f"{df['id'].duplicated().sum():,}"
        )

    if "external_id" in df.columns:

        lines.append(
            f"Unique external_id values: "
            f"{df['external_id'].nunique():,}"
        )

        lines.append(
            f"Duplicate external_id rows: "
            f"{df['external_id'].duplicated().sum():,}"
        )

    return lines


# ============================================================
# MISSING VALUES
# ============================================================

def missing_value_analysis(df):

    lines = [
        "",
        "=" * 70,
        "2. MISSING VALUE ANALYSIS",
        "=" * 70,
    ]

    for column in df.columns:

        count = int(
            df[column].isna().sum()
        )

        percentage = (
            count / len(df) * 100
            if len(df)
            else 0
        )

        lines.append(
            f"{column:<20}"
            f"{count:>8,}"
            f"  ({percentage:>6.2f}%)"
        )

    return lines


# ============================================================
# TEXT LENGTH ANALYSIS
# ============================================================

def text_length_analysis(df):

    lines = [
        "",
        "=" * 70,
        "3. TEXT LENGTH ANALYSIS",
        "=" * 70,
    ]

    columns = [
        "title",
        "content",
        "clean_title",
        "clean_content",
        "embedding_text",
    ]

    for column in columns:

        if column not in df.columns:
            continue

        lengths = (
            df[column]
            .fillna("")
            .astype(str)
            .str.len()
        )

        lines.extend([
            "",
            column,
            f"  Minimum: {lengths.min():.0f}",
            f"  Mean:    {lengths.mean():.2f}",
            f"  Median:  {lengths.median():.0f}",
            f"  75th %:  {lengths.quantile(.75):.0f}",
            f"  90th %:  {lengths.quantile(.90):.0f}",
            f"  95th %:  {lengths.quantile(.95):.0f}",
            f"  99th %:  {lengths.quantile(.99):.0f}",
            f"  Maximum: {lengths.max():.0f}",
        ])

        for threshold in [
            10,
            20,
            50,
            100,
            200,
        ]:

            count = int(
                (lengths < threshold).sum()
            )

            percentage = (
                count / len(df) * 100
                if len(df)
                else 0
            )

            lines.append(
                f"  < {threshold:>3} chars: "
                f"{count:>7,} "
                f"({percentage:>6.2f}%)"
            )

    return lines


# ============================================================
# SCORE ANALYSIS
# ============================================================

def score_analysis(df):

    lines = [
        "",
        "=" * 70,
        "4. SCORE / ENGAGEMENT ANALYSIS",
        "=" * 70,
    ]

    if "score" not in df.columns:

        lines.append(
            "score column not found."
        )

        return lines

    scores = pd.to_numeric(
        df["score"],
        errors="coerce",
    ).fillna(0)

    lines.extend([
        f"Minimum:        {scores.min():.2f}",
        f"Mean:           {scores.mean():.2f}",
        f"Median:         {scores.median():.2f}",
        f"75th percentile: {scores.quantile(.75):.2f}",
        f"90th percentile: {scores.quantile(.90):.2f}",
        f"95th percentile: {scores.quantile(.95):.2f}",
        f"99th percentile: {scores.quantile(.99):.2f}",
        f"Maximum:         {scores.max():.2f}",
        f"Zero-score posts: "
        f"{int((scores == 0).sum()):,}",
        f"Negative-score posts: "
        f"{int((scores < 0).sum()):,}",
    ])

    return lines


# ============================================================
# TEMPORAL ANALYSIS
# ============================================================

def temporal_analysis(df):

    lines = [
        "",
        "=" * 70,
        "5. TEMPORAL ANALYSIS",
        "=" * 70,
    ]

    if "published_at" not in df.columns:

        lines.append(
            "published_at column not found."
        )

        return lines

    dates = pd.to_datetime(
        df["published_at"],
        errors="coerce",
        utc=True,
    )

    invalid = int(
        dates.isna().sum()
    )

    valid = dates.dropna()

    lines.append(
        f"Invalid/missing dates: {invalid:,}"
    )

    if valid.empty:
        return lines

    lines.append(
        f"First post: {valid.min()}"
    )

    lines.append(
        f"Last post:  {valid.max()}"
    )

    lines.append(
        f"Time span:  "
        f"{valid.max() - valid.min()}"
    )

    # --------------------------------------------------------
    # Posts by year
    # --------------------------------------------------------

    yearly = (
        valid
        .dt.year
        .value_counts()
        .sort_index()
    )

    lines.append(
        "\nPOSTS BY YEAR"
    )

    for year, count in yearly.items():

        lines.append(
            f"  {year}: {count:,}"
        )

    # --------------------------------------------------------
    # Posts by month
    # --------------------------------------------------------

    monthly = (
        valid
        .dt.to_period("M")
        .value_counts()
        .sort_index()
    )

    lines.append(
        "\nPOSTS BY MONTH"
    )

    for month, count in monthly.items():

        lines.append(
            f"  {month}: {count:,}"
        )

    # --------------------------------------------------------
    # Daily density
    # --------------------------------------------------------

    daily = (
        valid
        .dt.floor("D")
        .value_counts()
        .sort_index()
    )

    full_range = pd.date_range(
        start=valid.min().floor("D"),
        end=valid.max().floor("D"),
        freq="D",
        tz="UTC",
    )

    lines.extend([
        "",
        "DAILY DENSITY",
        f"  Calendar days:     {len(full_range):,}",
        f"  Active days:       {len(daily):,}",
        f"  Zero-post days:    "
        f"{len(full_range) - len(daily):,}",
        f"  Mean posts/day:    {daily.mean():.2f}",
        f"  Median posts/day:  {daily.median():.2f}",
        f"  Maximum posts/day: {daily.max():,}",
    ])

    return lines


