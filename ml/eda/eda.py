# CREATE PLOTS
# ============================================================

def create_plots(df):

    print("\n" + "=" * 70)
    print("GENERATING EDA PLOTS")
    print("=" * 70)

    EDA_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    # --------------------------------------------------------
    # Embedding text length
    # --------------------------------------------------------

    if "embedding_text" in df.columns:

        lengths = (
            df["embedding_text"]
            .fillna("")
            .astype(str)
            .str.len()
        )

        upper = lengths.quantile(.99)

        plt.figure(
            figsize=(10, 6)
        )

        plt.hist(
            lengths[lengths <= upper],
            bins=50,
        )

        plt.xlabel("Characters")
        plt.ylabel("Number of Posts")
        plt.title(
            "Embedding Text Length Distribution"
        )

        plt.tight_layout()

        plt.savefig(
            EDA_DIR / "text_length_distribution.png",
            dpi=150,
        )

        plt.close()

    # --------------------------------------------------------
    # Title length
    # --------------------------------------------------------

    if "title" in df.columns:

        lengths = (
            df["title"]
            .fillna("")
            .astype(str)
            .str.len()
        )

        upper = lengths.quantile(.99)

        plt.figure(
            figsize=(10, 6)
        )

        plt.hist(
            lengths[lengths <= upper],
            bins=40,
        )

        plt.xlabel("Characters")
        plt.ylabel("Number of Posts")
        plt.title(
            "Title Length Distribution"
        )

        plt.tight_layout()

        plt.savefig(
            EDA_DIR / "title_length_distribution.png",
            dpi=150,
        )

        plt.close()

    # --------------------------------------------------------
    # Content length
    # --------------------------------------------------------

    if "content" in df.columns:

        lengths = (
            df["content"]
            .fillna("")
            .astype(str)
            .str.len()
        )

        upper = lengths.quantile(.99)

        plt.figure(
            figsize=(10, 6)
        )

        plt.hist(
            lengths[lengths <= upper],
            bins=50,
        )

        plt.xlabel("Characters")
        plt.ylabel("Number of Posts")
        plt.title(
            "Content Length Distribution"
        )

        plt.tight_layout()

        plt.savefig(
            EDA_DIR / "content_length_distribution.png",
            dpi=150,
        )

        plt.close()

    # --------------------------------------------------------
    # Score
    # --------------------------------------------------------

    if "score" in df.columns:

        scores = pd.to_numeric(
            df["score"],
            errors="coerce",
        ).fillna(0)

        upper = scores.quantile(.99)

        plt.figure(
            figsize=(10, 6)
        )

        plt.hist(
            scores[scores <= upper],
            bins=50,
        )

        plt.xlabel("Score")
        plt.ylabel("Number of Posts")
        plt.title(
            "Score Distribution up to 99th Percentile"
        )

        plt.tight_layout()

        plt.savefig(
            EDA_DIR / "score_distribution.png",
            dpi=150,
        )

        plt.close()

        # ----------------------------------------------------
        # Log-transformed score
        # ----------------------------------------------------

        plt.figure(
            figsize=(10, 6)
        )

        log_scores = scores.apply(
            lambda x: math.copysign(
                math.log10(abs(x) + 1),
                x,
            )
        )

        plt.hist(
            log_scores,
            bins=50,
        )

        plt.xlabel(
            "Signed log10(|score| + 1)"
        )

        plt.ylabel(
            "Number of Posts"
        )

        plt.title(
            "Log-Transformed Score Distribution"
        )

        plt.tight_layout()

        plt.savefig(
            EDA_DIR / "log_score_distribution.png",
            dpi=150,
        )

        plt.close()

    # --------------------------------------------------------
    # Posts by year / month / day
    # --------------------------------------------------------

    if "published_at" in df.columns:

        dates = pd.to_datetime(
            df["published_at"],
            errors="coerce",
            utc=True,
        ).dropna()

        if not dates.empty:

            # ------------------------------------------------
            # Posts by year
            # ------------------------------------------------

            yearly = (
                dates
                .dt.year
                .value_counts()
                .sort_index()
            )

            plt.figure(
                figsize=(12, 6)
            )

            plt.bar(
                yearly.index.astype(str),
                yearly.values,
            )

            plt.xlabel("Year")
            plt.ylabel("Number of Posts")
            plt.title("Posts by Year")
            plt.xticks(rotation=45)

            plt.tight_layout()

            plt.savefig(
                EDA_DIR / "posts_by_year.png",
                dpi=150,
            )

            plt.close()

            # ------------------------------------------------
            # Posts by month
            # ------------------------------------------------

            monthly = (
                dates
                .dt.to_period("M")
                .value_counts()
                .sort_index()
            )

            plt.figure(
                figsize=(14, 6)
            )

            plt.plot(
                monthly.index.astype(str),
                monthly.values,
            )

            plt.xlabel("Month")
            plt.ylabel("Number of Posts")
            plt.title("Posts by Month")

            step = max(
                1,
                len(monthly) // 15,
            )

            plt.xticks(
                range(
                    0,
                    len(monthly),
                    step,
                ),
                monthly.index.astype(str)[::step],
                rotation=45,
            )

            plt.tight_layout()

            plt.savefig(
                EDA_DIR / "posts_by_month.png",
                dpi=150,
            )

            plt.close()

            # ------------------------------------------------
            # Posts by day
            # ------------------------------------------------

            daily = (
                dates
                .dt.floor("D")
                .value_counts()
                .sort_index()
            )

            plt.figure(
                figsize=(14, 6)
            )

            plt.plot(
                daily.index,
                daily.values,
            )

            plt.xlabel("Date")
            plt.ylabel("Number of Posts")
            plt.title("Daily Post Volume")

            plt.tight_layout()

            plt.savefig(
                EDA_DIR / "posts_by_day.png",
                dpi=150,
            )

            plt.close()

    # --------------------------------------------------------
    # Domains
    # --------------------------------------------------------

    if "domain" in df.columns:

        domains = (
            df["domain"]
            .fillna("unknown")
            .astype(str)
            .value_counts()
            .head(15)
            .sort_values()
        )

        plt.figure(
            figsize=(10, 7)
        )

        plt.barh(
            domains.index,
            domains.values,
        )

        plt.xlabel("Number of Posts")
        plt.ylabel("Domain")
        plt.title("Top 15 Domains")

        plt.tight_layout()

        plt.savefig(
            EDA_DIR / "top_domains.png",
            dpi=150,
        )

        plt.close()

    # --------------------------------------------------------
    # Communities
    # --------------------------------------------------------

    if "community_id" in df.columns:

        communities = (
            df["community_id"]
            .fillna("unknown")
            .astype(str)
            .value_counts()
            .head(15)
            .sort_values()
        )

        plt.figure(
            figsize=(10, 7)
        )

        plt.barh(
            communities.index,
            communities.values,
        )

        plt.xlabel("Number of Posts")
        plt.ylabel("Community ID")
        plt.title("Top 15 Communities")

        plt.tight_layout()

        plt.savefig(
            EDA_DIR / "top_communities.png",
            dpi=150,
        )

        plt.close()

    print(
        f"Plots saved to:\n"
        f"    {EDA_DIR}"
    )


# ============================================================
# MAIN
# ============================================================

def main():

    df = load_data()

    lines = []

    lines.extend(
        basic_information(df)
    )

    lines.extend(
        missing_value_analysis(df)
    )

    lines.extend(
        text_length_analysis(df)
    )

    lines.extend(
        score_analysis(df)
    )

    lines.extend(
        temporal_analysis(df)
    )

    lines.extend(
        community_analysis(df)
    )

    lines.extend(
        domain_analysis(df)
    )

    lines.extend(
        duplicate_content_analysis(df)
    )

    lines.extend(
        sample_analysis(df)
    )

    report = "\n".join(lines)

    print("\n")
    print(report)

    EDA_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    SUMMARY_FILE.write_text(
        report,
        encoding="utf-8",
    )

    create_plots(df)

    print("\n" + "=" * 70)
    print("EDA COMPLETE")
    print("=" * 70)

    print(
        f"\nSummary:"
        f"\n    {SUMMARY_FILE}"
    )

    print(
        f"\nPlots:"
        f"\n    {EDA_DIR}"
    )


if __name__ == "__main__":
    main()